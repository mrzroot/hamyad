export const MEMORY_HEAD = "<!-- hamyad:memory v1 — one-file project memory. The brief at the top is regenerated on every change; the entries below it are the data. Edit an entry block (or use hamyad / brain_* tools), not the brief. -->";
export const ENTRIES_MARK = "<!-- hamyad:entries -->";
export const fileOpen = (p: string) => `<!-- hamyad:file ${p} -->`;
export const FILE_CLOSE = "<!-- hamyad:/file -->";

/** Escape our own markers inside stored content so a block cannot end early. */
export const escapeMarkers = (s: string) => s.replace(/<!-- hamyad:/g, "<!-- hamyad\\:");
export const unescapeMarkers = (s: string) => s.replace(/<!-- hamyad\\:/g, "<!-- hamyad:");

/**
 * A single self-contained Markdown file: readable brief on top, every entry
 * below. Upload it to any chat tool that only takes files (ChatGPT/Claude
 * Projects, Gemini Gems, NotebookLM…), or use it *as* the store in a
 * Dropbox / Google Drive / iCloud folder (`hamyad init --store ~/Dropbox/x/MEMORY.md`).
 */
export function renderMemoryMd(config: BrainConfig, entries: Entry[], files: { path: string; content: string }[]): string {
  const brief = renderBrief(config, entries, { maxChars: 100_000 });
  const blocks = [...files]
    .filter((f) => f.path !== "MEMORY.md" && f.path !== "BRAIN.md")
    .sort((a, b) => a.path.localeCompare(b.path))
    .map((f) => `${fileOpen(f.path)}\n${escapeMarkers(f.content.replace(/\s+$/, ""))}\n${FILE_CLOSE}`);
  return [MEMORY_HEAD, brief.trim(), "", "---", "", "## All entries", "", ENTRIES_MARK, ...blocks, ""].join("\n");
}

/** Parse the entry blocks out of a MEMORY.md. Text outside blocks (the brief) is ignored. */
export function parseMemoryMd(text: string): { path: string; content: string }[] {
  const out: { path: string; content: string }[] = [];
  const re = /<!-- hamyad:file ([^\s]+) -->\r?\n([\s\S]*?)\r?\n?<!-- hamyad:\/file -->/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(text))) out.push({ path: m[1], content: unescapeMarkers(m[2]) + "\n" });
  return out;
}
